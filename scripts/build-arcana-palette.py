"""Build the playable city's palette LUT and shader from its editable GPL.

The preserved 2D sprite kit keeps its original arcana-64.gpl palette. This world
palette follows the original illustrated city, without rebaking those sprites.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
PALETTE = ROOT / "godot-arcana/art/source/arcana-world-64.gpl"
OUTPUT = ROOT / "godot-arcana/art/export/arcana-palette-lut.png"
SHADER = ROOT / "godot-arcana/art/resources/pixel3d_palette.gdshader"

def main():
    colors = []
    for line in PALETTE.read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if len(parts) >= 3 and all(value.isdigit() for value in parts[:3]):
            colors.append(tuple(map(int, parts[:3])))
    if len(colors) != 64 or len(set(colors)) != 64:
        raise ValueError("Expected 64 distinct world colors")
    image = Image.new("RGB", (1024, 32))
    pixels = image.load()
    for b in range(32):
        for g in range(32):
            for r in range(32):
                rgb = (r * 255 / 31, g * 255 / 31, b * 255 / 31)
                nearest = min(colors, key=lambda c: .30*(c[0]-rgb[0])**2 + .59*(c[1]-rgb[1])**2 + .11*(c[2]-rgb[2])**2)
                pixels[b * 32 + r, g] = nearest
    image.save(OUTPUT, optimize=True)
    SHADER.write_text('''shader_type canvas_item;
// Generated by scripts/build-arcana-palette.py. Sample the completed world texture.
uniform sampler2D palette_lut : filter_nearest, repeat_disable;
uniform bool palette_enabled = true;
void fragment() {
    vec4 world = texture(TEXTURE, UV);
    if (palette_enabled) {
        vec3 source = clamp(world.rgb, vec3(0.0), vec3(1.0));
        vec3 cell = floor(source * 31.0 + 0.5);
        vec2 uv = vec2((cell.b * 32.0 + cell.r + 0.5) / 1024.0, (cell.g + 0.5) / 32.0);
        COLOR = vec4(textureLod(palette_lut, uv, 0.0).rgb, world.a);
    } else {
        COLOR = world;
    }
}
''', encoding='utf-8')
    print("Arcana royal city palette ready: 64 colors, 1024 x 32, one LUT pass")

if __name__ == "__main__":
    main()
